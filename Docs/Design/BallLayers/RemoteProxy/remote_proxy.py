"""T56 offline consumer for synthetic confirmed-decoration summaries only.

This is not wired to T51, a network transport, a gameplay ledger, or colliders.
All identity/revision/sequence values are supplied by the synthetic upstream
fixture; this module never allocates or increments them.
"""
from dataclasses import dataclass, replace
import math
from typing import Iterable, Tuple

Vector3 = Tuple[float, float, float]
Quaternion = Tuple[float, float, float, float]


class SummaryError(ValueError):
    """Malformed synthetic input; no cache mutation has occurred."""


class SummaryConflictError(SummaryError):
    """One upstream identity/revision was reused with different content."""


class ProxyCapacityError(SummaryError):
    """A bounded visual-only table cannot accept more records."""


def _text(value, name: str) -> str:
    if not isinstance(value, str) or not value:
        raise SummaryError(f"{name} must be a non-empty string")
    return value


def _uint(value, name: str, maximum: int) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or value < 0 or value > maximum:
        raise SummaryError(f"{name} must be an unsigned integer in range")
    return value


def _finite_vector(value, length: int, name: str) -> tuple:
    if not isinstance(value, (tuple, list)) or len(value) != length:
        raise SummaryError(f"{name} must have {length} components")
    result = []
    for component in value:
        if isinstance(component, bool) or not isinstance(component, (int, float)):
            raise SummaryError(f"{name} must contain real numbers")
        converted = float(component)
        if not math.isfinite(converted):
            raise SummaryError(f"{name} must be finite")
        result.append(converted)
    return tuple(result)


def _unit_quaternion(value) -> Quaternion:
    parts = _finite_vector(value, 4, "rotation")
    scale = max(abs(component) for component in parts)
    if scale == 0.0:
        raise SummaryError("rotation quaternion must be non-zero")
    scaled = tuple(component / scale for component in parts)
    norm = math.sqrt(sum(component * component for component in scaled))
    if not math.isfinite(norm) or scale <= 1e-12 / norm:
        raise SummaryError("rotation quaternion norm is too small")
    return (scaled[0] / norm, scaled[1] / norm,
            scaled[2] / norm, scaled[3] / norm)


@dataclass(frozen=True)
class SyntheticConfirmedSummary:
    """Mock contract: identity and digest are opaque upstream-provided values.

    ``attach_sequence`` and ``event_id`` are never generated by this consumer.
    The digest is a conflict-detection token in the fixture, not authentication.
    """
    context_id: str
    ball_id: str
    instance_id: str
    generation: int
    attach_sequence: int
    event_id: str
    revision: int
    summary_digest: str
    variant_id: str
    variant_seed: int
    position: Vector3
    rotation: Quaternion = (0.0, 0.0, 0.0, 1.0)
    visible: bool = True
    buried: bool = False
    removed: bool = False
    presentation_priority: int = 0

    @property
    def identity_key(self) -> tuple:
        """Stable identity supplied by the fixture; never a local slot/index."""
        return (self.context_id, self.ball_id, self.instance_id,
                self.generation, self.attach_sequence)

    @property
    def source_event_key(self) -> tuple:
        return self.identity_key + (self.event_id,)


class RemoteProxyCache:
    """Bounded visual cache; no ledger, physics, collider, or score interface."""
    def __init__(self, max_records: int, renderer_budget: int):
        if (isinstance(max_records, bool) or not isinstance(max_records, int)
                or max_records <= 0):
            raise ValueError("max_records must be a positive integer")
        if (isinstance(renderer_budget, bool) or not isinstance(renderer_budget, int)
                or renderer_budget < 0):
            raise ValueError("renderer_budget must be a non-negative integer")
        self.max_records = max_records
        self.renderer_budget = renderer_budget
        self._records: dict[tuple, SyntheticConfirmedSummary] = {}
        self._generation_high_water: dict[tuple, int] = {}
        self._cleared_contexts: set[str] = set()

    @staticmethod
    def _validated(summary: SyntheticConfirmedSummary) -> SyntheticConfirmedSummary:
        if not isinstance(summary, SyntheticConfirmedSummary):
            raise SummaryError("input must be a SyntheticConfirmedSummary")
        _text(summary.context_id, "context_id")
        _text(summary.ball_id, "ball_id")
        _text(summary.instance_id, "instance_id")
        _text(summary.event_id, "event_id")
        _text(summary.summary_digest, "summary_digest")
        _text(summary.variant_id, "variant_id")
        _uint(summary.generation, "generation", (1 << 32) - 1)
        _uint(summary.attach_sequence, "attach_sequence", (1 << 64) - 1)
        _uint(summary.revision, "revision", (1 << 32) - 1)
        _uint(summary.variant_seed, "variant_seed", (1 << 64) - 1)
        if (isinstance(summary.presentation_priority, bool)
                or not isinstance(summary.presentation_priority, int)
                or summary.presentation_priority < 0):
            raise SummaryError("presentation_priority must be a non-negative integer")
        if any(not isinstance(flag, bool) for flag in (summary.visible, summary.buried, summary.removed)):
            raise SummaryError("visible, buried and removed must be bools")
        position = _finite_vector(summary.position, 3, "position")
        rotation = _unit_quaternion(summary.rotation)
        return replace(summary, position=position, rotation=rotation)

    @staticmethod
    def _base_key(summary: SyntheticConfirmedSummary) -> tuple:
        return (summary.context_id, summary.ball_id, summary.instance_id)

    def _check_capacity(self, records_after_purge: int, base_exists: bool) -> None:
        if records_after_purge >= self.max_records:
            raise ProxyCapacityError("synthetic summary table is full")
        if not base_exists and len(self._generation_high_water) >= self.max_records:
            raise ProxyCapacityError("generation high-water table is full")

    def apply(self, incoming: SyntheticConfirmedSummary) -> str:
        """Consume one synthetic confirmation atomically; return a disposition."""
        summary = self._validated(incoming)
        if summary.context_id in self._cleared_contexts:
            return "cleared_context"
        key = summary.identity_key
        base = self._base_key(summary)
        high = self._generation_high_water.get(base)
        if high is not None and summary.generation < high:
            return "stale_generation"

        previous = self._records.get(key)
        if previous is not None:
            if previous.event_id != summary.event_id:
                raise SummaryConflictError("stable attachment identity has conflicting event_id")
            if summary.revision < previous.revision:
                return "stale_revision"
            if summary.revision == previous.revision:
                if summary == previous:
                    return "duplicate"
                raise SummaryConflictError("same identity/revision has conflicting summary")
            if previous.removed:
                return "removed_tombstone"
            # Newer upstream revision may update presentation data or tombstone it.
            self._records[key] = summary
            return "updated"

        purge_keys = []
        if high is not None and summary.generation > high:
            purge_keys = [stored_key for stored_key in self._records
                          if stored_key[:3] == base and stored_key[3] < summary.generation]
        self._check_capacity(len(self._records) - len(purge_keys), high is not None)

        # Commit only after validation, conflict checks and all capacity checks.
        for stored_key in purge_keys:
            del self._records[stored_key]
        if high is None or summary.generation > high:
            self._generation_high_water[base] = summary.generation
        self._records[key] = summary
        return "accepted"

    @property
    def summaries(self) -> tuple[SyntheticConfirmedSummary, ...]:
        return tuple(self._records[key] for key in sorted(self._records))

    @property
    def rendered_summaries(self) -> tuple[SyntheticConfirmedSummary, ...]:
        candidates = [summary for summary in self._records.values()
                      if not summary.removed and summary.visible and not summary.buried]
        candidates.sort(key=lambda summary: (-summary.presentation_priority,
                                            summary.identity_key, summary.event_id))
        return tuple(candidates[:self.renderer_budget])

    @property
    def renderer_count(self) -> int:
        return len(self.rendered_summaries)

    @property
    def merged_buried_count(self) -> int:
        """Logical buried-summary count; it does not allocate a Renderer."""
        return sum(1 for summary in self._records.values()
                   if summary.buried and not summary.removed)

    @property
    def tracked_count(self) -> int:
        return len(self._records)

    def clear_context(self, context_id: str) -> int:
        context = _text(context_id, "context_id")
        if context not in self._cleared_contexts and len(self._cleared_contexts) >= self.max_records:
            raise ProxyCapacityError("closed-context tombstone table is full")
        removed = [key for key in self._records if key[0] == context]
        for key in removed:
            del self._records[key]
        self._generation_high_water = {
            base: generation for base, generation in self._generation_high_water.items()
            if base[0] != context
        }
        # A new round must use a new context identity; old packets cannot revive.
        self._cleared_contexts.add(context)
        return len(removed)

    def rebuild_context(self, context_id: str,
                        snapshot: Iterable[SyntheticConfirmedSummary]) -> None:
        """Atomically replace one context from a complete synthetic snapshot."""
        context = _text(context_id, "context_id")
        if context in self._cleared_contexts:
            raise SummaryError("a cleared context cannot be rebuilt; use a new context id")
        incoming = tuple(self._validated(summary) for summary in snapshot)
        if any(summary.context_id != context for summary in incoming):
            raise SummaryError("snapshot contains a different context id")

        candidate = RemoteProxyCache(self.max_records, self.renderer_budget)
        # Stable ordering makes generation/revision resolution independent of arrival order.
        ordered = sorted(incoming, key=lambda item: (item.context_id, item.ball_id,
                         item.instance_id, item.generation, item.attach_sequence,
                         item.revision, item.event_id))
        for summary in ordered:
            candidate.apply(summary)
        other_records = {key: value for key, value in self._records.items() if key[0] != context}
        other_high = {key: value for key, value in self._generation_high_water.items()
                      if key[0] != context}
        merged_records = dict(other_records)
        merged_records.update(candidate._records)
        merged_high = dict(other_high)
        merged_high.update(candidate._generation_high_water)
        if len(merged_records) > self.max_records or len(merged_high) > self.max_records:
            raise ProxyCapacityError("rebuilt snapshot exceeds bounded cache capacity")
        # Candidate construction above is isolated; swap only after every record validates.
        self._records = merged_records
        self._generation_high_water = merged_high
