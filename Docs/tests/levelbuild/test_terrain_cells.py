"""Guards for the four procedural terrain cells C21-C24.

The geometry is generated by ``Tools/levelbuild/physics_test_terrain.py`` and stored as
v2 placement documents; the criteria rows are in ``physics_test_field.json``. These tests
pin the four ids, their triangle counts, the §7 terrain invariants and the fact that the
cells are still unwired (no PhysicsTestField.unity edit in this change).
"""

import json
import math
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from Tools.levelbuild import placement_v2 as v2  # noqa: E402
FIELD = ROOT / "Docs/Design/BallMotor/physics_test_field.json"
LEVELS = ROOT / "Docs/Design/Levels/physics_test_field"
CELL_IDS = ("C21", "C22", "C23", "C24")
EXPECTED_TRIANGLES = {"C21": 14, "C22": 14, "C23": 8, "C24": 12}
EXPECTED_VERTICES = {"C21": 28, "C22": 28, "C23": 16, "C24": 24}


def field():
    return json.loads(FIELD.read_text(encoding="utf-8"))


def cell_doc(cell_id):
    return json.loads((LEVELS / cell_id / "placement.json").read_text(encoding="utf-8"))


class TerrainCellData(unittest.TestCase):
    def test_exact_four_cells_are_planned_terrain_pending(self):
        rows = [cell for cell in field()["planned_cells"]
                if cell.get("status") == "terrain_pending"]
        self.assertEqual([cell["id"] for cell in rows], list(CELL_IDS))
        for cell in rows:
            self.assertFalse(cell["wired"])
            self.assertEqual(cell["placement"],
                             "physics_test_field/%s/placement.json" % cell["id"])
            self.assertEqual(cell["terrain"]["triangles"], EXPECTED_TRIANGLES[cell["id"]])

    def test_triangle_and_vertex_counts_are_pinned(self):
        for cell_id in CELL_IDS:
            doc = cell_doc(cell_id)
            terrain = doc["terrain"]
            self.assertEqual(terrain["triangles"]["count"], EXPECTED_TRIANGLES[cell_id])
            self.assertEqual(len(terrain["indices"]) // 3, EXPECTED_TRIANGLES[cell_id])
            self.assertEqual(len(terrain["vertices"]), EXPECTED_VERTICES[cell_id])
            self.assertEqual(doc["meta"]["expected"]["terrainTriangles"],
                             EXPECTED_TRIANGLES[cell_id])

    def test_v2_schema_and_inline_geometry(self):
        for cell_id in CELL_IDS:
            doc = cell_doc(cell_id)
            self.assertEqual(doc["schema"], "katamari.placement/2")
            self.assertEqual(doc["meta"]["units"], "m")
            self.assertEqual(doc["meta"]["convention"],
                             "unity-y-up-left-handed-quat-xyzw")
            terrain = doc["terrain"]
            self.assertEqual(terrain["kind"], "mesh")
            self.assertEqual(terrain["winding"], "ccw")
            self.assertNotIn("meshRef", terrain)
            self.assertIn("vertices", terrain)
            self.assertIn("indices", terrain)

    def test_zone_and_class_arrays_are_triangle_aligned(self):
        for cell_id in CELL_IDS:
            terrain = cell_doc(cell_id)["terrain"]
            count = terrain["triangles"]["count"]
            self.assertEqual(len(terrain["triangles"]["zoneIds"]), count)
            self.assertEqual(len(terrain["triangles"]["classes"]), count)
            self.assertTrue(all(value in (1, 2, 3)
                                for value in terrain["triangles"]["classes"]))

    def test_chunks_and_broadphase_cover_every_triangle_once(self):
        for cell_id in CELL_IDS:
            terrain = cell_doc(cell_id)["terrain"]
            count = terrain["triangles"]["count"]
            ranges = [chunk["triangleRange"] for chunk in terrain["chunks"]]
            self.assertEqual(ranges[0][0], 0)
            for start, length in ranges:
                self.assertGreaterEqual(start, 0)
                self.assertGreater(length, 0)
                self.assertLessEqual(length, 512)
            self.assertEqual(sum(length for _, length in ranges), count)
            boxes = terrain["broadPhase"]["boxes"]
            self.assertEqual(sum(box["triangleRange"][1] for box in boxes), count)
            low = min(vertex[1] for vertex in terrain["vertices"])
            self.assertLess(doc(cell_id)["meta"]["groundY"], low)

    def test_material_segments_cover_all_indices(self):
        for cell_id in CELL_IDS:
            terrain = cell_doc(cell_id)["terrain"]
            segments = terrain["materialSegments"]
            self.assertEqual(segments[0]["firstIndex"], 0)
            self.assertEqual(segments[-1]["firstIndex"] + segments[-1]["indexCount"],
                             len(terrain["indices"]))

    def test_every_terrain_placement_passes_the_gate(self):
        # These four cells are unwired, so the wired-cell gate test never sees them. They are
        # real v2 placements all the same, and the [terrain_grid] rule in particular was only
        # ever exercised here by accident: the generator's grid origin sat 1 mm inside the
        # broad-phase minimum. Validate them explicitly.
        for cell_id in CELL_IDS:
            path = LEVELS / cell_id / "placement.json"
            doc = json.loads(path.read_text(encoding="utf-8"))
            report = v2.validate(doc, path=path)
            self.assertTrue(report.ok, "%s: %s" % (path, report.errors))
            self.assertEqual(report.warnings, [], path)

    def test_criteria_use_four_diameter_rows_and_known_ops(self):
        rows = [cell for cell in field()["planned_cells"]
                if cell.get("status") == "terrain_pending"]
        for cell in rows:
            self.assertEqual(len(cell["drive"]), 2)
            self.assertGreater(cell["stop_seconds"], 0)
            for check in cell["design_checks"]:
                self.assertEqual(len(check["expect"]), 4)
                self.assertIn(check["op"], ("abs<=", "<=", ">=", "==", "abs>="))
                self.assertIn("pass", check["expect"])

    def test_geometry_stays_inside_its_own_footprint(self):
        for cell in [c for c in field()["planned_cells"]
                     if c.get("status") == "terrain_pending"]:
            doc = cell_doc(cell["id"])
            low = cell["footprint"]["center"][0] - cell["footprint"]["size"][0] * 0.5
            high = cell["footprint"]["center"][0] + cell["footprint"]["size"][0] * 0.5
            for vertex in doc["terrain"]["vertices"]:
                self.assertGreaterEqual(vertex[0], low - 0.001, cell["id"])
                self.assertLessEqual(vertex[0], high + 0.001, cell["id"])


def doc(cell_id):
    return cell_doc(cell_id)


if __name__ == "__main__":
    unittest.main()
